import os
import re
import json

def list_missing(folder):
    missing_files = []

    for root, dirs, files in os.walk(folder):
        for file in files:
            if file.endswith('.go') and not file.endswith('_test.go'):
                if "proto" in root or "examples" in root or "tests" in root or "mock" in root or "testdata" in root:
                    continue

                filepath = os.path.join(root, file)
                with open(filepath, 'r') as f:
                    content = f.read()

                if "Code generated by" in content or "DO NOT EDIT" in content:
                    continue

                # If there are any missing docs based on our simple check:
                # regex to find exported functions/methods
                decls = re.finditer(r'(?:^\s*//.*$\n)*^func\s+(?:(?:\([^)]+\)\s+)|)([A-Z]\w*)', content, re.MULTILINE)
                has_missing = False
                for match in decls:
                    if '// Summary:' not in match.group(0):
                        has_missing = True
                        break

                if not has_missing:
                    types = re.finditer(r'(?:^\s*//.*$\n)*^type\s+([A-Z]\w*)', content, re.MULTILINE)
                    for match in types:
                        if '// Summary:' not in match.group(0):
                            has_missing = True
                            break

                if not has_missing:
                    vars_ = re.finditer(r'(?:^\s*//.*$\n)*^var\s+([A-Z]\w*)', content, re.MULTILINE)
                    for match in vars_:
                        if '// Summary:' not in match.group(0):
                            has_missing = True
                            break

                if not has_missing:
                    consts = re.finditer(r'(?:^\s*//.*$\n)*^const\s+([A-Z]\w*)', content, re.MULTILINE)
                    for match in consts:
                        if '// Summary:' not in match.group(0):
                            has_missing = True
                            break

                if has_missing:
                    missing_files.append(filepath)

    return missing_files

missing = list_missing("server/pkg")
with open("missing_files.json", "w") as f:
    json.dump(missing, f)
