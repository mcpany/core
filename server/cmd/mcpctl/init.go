package main

import (
	"fmt"
	"os"

	"github.com/spf13/cobra"
)

func newInitCmd() *cobra.Command {
	var outputPath string
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Interactively generate a valid configuration file",
		RunE: func(cmd *cobra.Command, _ []string) error {
			// A very simple interactive wizard simulation for now.
			// Ideally we would use a library like survey or promptui.
			fmt.Fprintln(cmd.OutOrStdout(), "Generating default MCP Any configuration...")

			defaultConfig := `global_settings:
  bind_address: ":50050"
  mcp_listen_address: ":50055"
  log_level: "info"
  api_key: "CHANGE_ME"

upstream_services:
  - name: "example-service"
    description: "An example service generated by mcpctl init"
    command_line_service:
      command: "echo"
      args: ["hello world"]
`
			if outputPath == "" {
				outputPath = "config.yaml"
			}

			// Check if file exists
			if _, err := os.Stat(outputPath); err == nil {
				return fmt.Errorf("file %s already exists, aborting", outputPath)
			}

			if err := os.WriteFile(outputPath, []byte(defaultConfig), 0644); err != nil {
				return fmt.Errorf("failed to write config to %s: %w", outputPath, err)
			}

			fmt.Fprintf(cmd.OutOrStdout(), "Configuration written to %s\n", outputPath)
			return nil
		},
	}
	cmd.Flags().StringVarP(&outputPath, "output", "o", "config.yaml", "Path to save the generated config")
	return cmd
}
